/** Unique per run so tests never collide on a unique email constraint. */
export function uniqueEmail(prefix = 'e2e'): string {
  return `${prefix}-${Date.now()}-${Math.floor(Math.random() * 1e6)}@example.test`;
}

/**
 * Unique per run, and this matters more than it looks.
 *
 * Duplicate detection matches a submission against existing enquiries by
 * **email OR the last ten digits of the phone number** within a 15-minute
 * window. A fixed test phone number therefore made every run after the first
 * return the earlier enquiry with `duplicate: true` instead of exercising the
 * happy path — the suite passed for the wrong reason. Emails are already
 * unique; phone numbers must be too.
 */
export function uniquePhone(): string {
  const digits = String(Math.floor(1000000 + Math.random() * 8999999));
  return `+91 9${digits}`;
}

export async function signInAs(
  page: Page,
  credentials: { email: string; password: string },
): Promise<void> {
  const response = await page.context().request.post('/api/auth/sign-in/email', {
    data: { email: credentials.email, password: credentials.password },
  });

  if (!response.ok()) {
    throw new Error(
      `Sign-in failed for ${credentials.email}: ${response.status()} ${await response.text()}`,
    );
  }
}

export async function signOut(page: Page): Promise<void> {
  await page.context().request.post('/api/auth/sign-out', { data: {} });
  await page.context().clearCookies();
}

/** Registers a brand-new customer and leaves the session cookie in the jar. */
export async function registerNewCustomer(
  page: Page,
  options: { name?: string; password?: string } = {},
): Promise<{ email: string; password: string; name: string }> {
  const email = uniqueEmail('customer');
  const password = options.password ?? 'E2ePassw0rd!';
  const name = options.name ?? 'E2E Customer';

  const response = await page.context().request.post('/api/auth/sign-up/email', {
    data: { email, password, name },
  });

  if (!response.ok()) {
    throw new Error(`Sign-up failed: ${response.status()} ${await response.text()}`);
  }

  return { email, password, name };
}

/**
 * Opens the enquiry dialog from a listing profile.
 *
 * The form is a modal now, so every journey starts with this trigger. Scoping
 * the returned locator to the dialog also keeps `getByLabel` from matching the
 * dialog title or the page behind it.
 */
export async function openEnquiryDialog(page: Page) {
  await page
    .getByRole('button', { name: /^send an enquiry$/i })
    .first()
    .click();
  const dialog = page.getByRole('dialog');
  await expect(dialog).toBeVisible({ timeout: 30_000 });
  return dialog;
}

/**
 * Sends an enquiry from a listing's own profile dialog.
 *
 * Every enquiry belongs to exactly one listing, so the journey is "open the
 * profile, open the dialog, fill the four required fields, send". Returns the
 * reference code shown on the confirmation.
 */
export async function submitListingEnquiry(
  page: Page,
  slug: string,
  options: { name?: string; email?: string; phone?: string; consent?: boolean } = {},
): Promise<string> {
  await page.goto(`/vendors/${slug}`);
  const dialog = await openEnquiryDialog(page);

  await dialog.getByLabel('Full name').fill(options.name ?? 'E2E Guest');
  await dialog.getByLabel('Contact number').fill(options.phone ?? uniquePhone());
  await dialog.getByLabel('Email address').fill(options.email ?? uniqueEmail('guest'));

  if (options.consent !== false) {
    await dialog.getByLabel(/privacy terms/i).check();
  }
  await dialog.getByRole('button', { name: /^send enquiry$/i }).click();

  const reference = dialog.getByText(/LE-[A-Z0-9]{8}/);
  await expect(reference).toBeVisible({ timeout: 30_000 });
  return (await reference.innerText()).trim();
}

/** Fails the test with a readable message when a page renders an error boundary. */
export async function expectNoErrorBoundary(page: Page): Promise<void> {
  const errorHeading = page.getByRole('heading', { name: /something went wrong/i });
  await expect(errorHeading).toHaveCount(0);
}

/**
 * Waits for the results grid or the empty state — whichever the data produces.
 *
 * The grid is a `<ul aria-label="Search results">` (a real list, not an ARIA
 * region), so the assertion targets the named list and falls back to the empty
 * state's own copy.
 */
export async function expectResultsOrEmptyState(page: Page): Promise<void> {
  // A listing card is an `<article>` on every surface; the grid's accessible
  // name differs between the search page ("Search results") and a category
  // landing page ("<Category> listings"), so the card itself is the stable hook.
  const results = page.locator('article').first();
  const empty = page.getByText(/No businesses match these filters|No .*(match|found)/i).first();
  // 30s: under Partial Prerendering the shell arrives before the streamed
  // results, so an immediate read sees a skeleton.
  await expect(results.or(empty).first()).toBeVisible({ timeout: 30_000 });
}

export function listingCards(page: Page) {
  return page.locator('article');
}

/** The results header total, e.g. `… of 19 businesses` → `19`. */
export async function getResultTotal(page: Page): Promise<number> {
  const summary = page.getByText(/of\s+[\d,]+\s+businesses?/i).first();
  await expect(summary).toBeVisible();
  const text = await summary.innerText();
  const match = text.match(/of\s+([\d,]+)/i);
  if (!match) throw new Error(`Could not read a result total from: ${text}`);
  return Number(match[1].replace(/,/g, ''));
}

/** The visible name on the first result card. */
export async function firstCardName(page: Page): Promise<string> {
  return (await listingCards(page).first().locator('h3').innerText()).trim();
}

/**
 * Fails when a page rendered an error surface.
 *
 * Deliberately text-based rather than `getByRole('alert')`: `role="alert"` is a
 * legitimate live-region role that this product uses for real things (a
 * notification, a form error summary), so asserting zero alert nodes fails on
 * healthy pages. What actually matters is that no *failure* message is showing,
 * which is what the framework boundary and the application's own `ErrorState`
 * both produce.
 */
export async function expectNoErrorState(page: Page): Promise<void> {
  await expect(page.getByText(/could not load|failed to load|something went wrong/i)).toHaveCount(
    0,
  );
  await expectNoErrorBoundary(page);
}

/**
 * Asserts the page does not scroll horizontally, which is a real responsive
 * regression class on filter-heavy pages.
 */
export async function expectNoHorizontalOverflow(page: Page): Promise<void> {
  const overflow = await page.evaluate(
    () => document.documentElement.scrollWidth - document.documentElement.clientWidth,
  );
  expect(overflow, 'page should not scroll horizontally').toBeLessThanOrEqual(1);
}

